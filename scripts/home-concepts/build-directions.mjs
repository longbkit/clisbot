import { readFile, writeFile, mkdir } from "node:fs/promises";
import { transform } from "esbuild";

// Each review file contains the same browser-only fixture, with a separate layout.
const root = new URL("../../", import.meta.url);
const base = new URL("docs/audits/2026-10-09-home-concepts/", root);
const folder = new URL("directions/", base);
await mkdir(folder, { recursive: true });
const scripts = [
  "data.js",
  "views.js",
  "app.js",
  "actions.js",
  "combined-icons.js",
  "combined-model.js",
  "combined-views.js",
  "combined-actions.js",
  "directions/model.js",
  "directions/views.js",
  "directions/layouts.js",
  "directions/actions.js",
];
const styles = ["styles.css", "combined.css", "directions/styles.css"];
const [template, js, css] = await Promise.all([
  readFile(new URL("template.html", folder), "utf8"),
  Promise.all(scripts.map((file) => readFile(new URL(file, base), "utf8"))),
  Promise.all(styles.map((file) => readFile(new URL(file, base), "utf8"))),
]);
const style = await transform(css.join("\n").replace(/@font-face\s*\{[^}]*\}/, ""), {
  loader: "css",
  minify: true,
});
const names = ["Bắt đầu nhanh", "Theo Project", "Nhịp công việc", "Home · Tổng hòa"];
const files = ["01-chat.html", "02-project.html", "03-today.html", "04-home.html"];
for (let i = 0; i < files.length; i++) {
  const source = js
    .join("\n")
    .replaceAll("clisbot-home-combined-v2", `clisbot-home-direction-${i + 1}`)
    .replaceAll("clisbot-home-design-v1", `clisbot-home-direction-base-${i + 1}`);
  const script = await transform(source, {
    loader: "js",
    minifyWhitespace: true,
    minifySyntax: true,
    target: "es2020",
  });
  const html = template
    .replaceAll("{{number}}", String(i + 1))
    .replaceAll("{{name}}", names[i])
    .replace("</head>", `<style>${style.code}</style></head>`)
    .replace(
      "</body>",
      `<script>${script.code.replaceAll("</script", "<\\/script")}</script></body>`,
    );
  await writeFile(
    new URL(files[i], folder),
    `<!-- Generated by build-directions.mjs; edit sources. -->\n${html}`,
  );
  console.log(`${files[i]} · ${Math.round(Buffer.byteLength(html) / 1024)} KiB · offline`);
}
