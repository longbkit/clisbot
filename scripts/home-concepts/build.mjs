import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { transform } from "esbuild";

// Portable review artifacts; provider symbols come from the app's existing assets.
const root = new URL("../../", import.meta.url);
const folder = new URL("docs/audits/2026-10-09-home-concepts/", root);
const common = ["data.js", "views.js", "app.js", "actions.js"];
const providerPaths = {
  "Claude Code": "packages/app/assets/icons/claude.svg",
  Codex: "packages/app/assets/icons/codex.svg",
  OpenCode: "packages/app/src/assets/acp-provider-icons/opencode.svg",
};
const providerSvg = Object.fromEntries(
  await Promise.all(
    Object.entries(providerPaths).map(async ([name, path]) => [
      name,
      (await readFile(new URL(path, root), "utf8")).replace(/<title>.*?<\/title>/g, "").trim(),
    ]),
  ),
);
await writeFile(
  new URL("combined-icons.js", folder),
  `/* Generated from current app assets by scripts/home-concepts/build.mjs. */\nHOME.providerSvg = ${JSON.stringify(providerSvg, null, 2)};\n`,
);
async function build(input, output, styles, scripts, embeddedFont = false) {
  const html = await readFile(new URL(input, folder), "utf8");
  let css = (await Promise.all(styles.map((file) => readFile(new URL(file, folder), "utf8")))).join(
    "\n",
  );
  let license = "";
  if (embeddedFont) {
    const font = await readFile(
      new URL("assets/branding/clisbot/fonts/Manrope-Variable.ttf", root),
    );
    css = css.replace(
      "url('../../../assets/branding/clisbot/fonts/Manrope-Variable.ttf')",
      `url('data:font/ttf;base64,${font.toString("base64")}')`,
    );
    license = `<!-- Embedded Manrope font license:\n${await readFile(new URL("assets/branding/clisbot/fonts/OFL.txt", root), "utf8")}\n-->\n`;
  } else css = css.replace(/@font-face\s*\{[^}]*\}/, "");
  const source = (
    await Promise.all(scripts.map((file) => readFile(new URL(file, folder), "utf8")))
  ).join("\n");
  const [style, script] = await Promise.all([
    transform(css, { loader: "css", minify: true }),
    transform(source, {
      loader: "js",
      minifyWhitespace: true,
      minifySyntax: true,
      target: "es2020",
    }),
  ]);
  const portable = html
    .replace(/\s*<link rel="stylesheet" href="[^"]+"\s*\/>/g, "")
    .replace("</head>", `<style>${style.code}</style>\n</head>`)
    .replace(/\s*<script defer src="[^"]+"><\/script>/g, "")
    .replace(
      "</body>",
      `<script>${script.code.replaceAll("</script", "<\\/script")}</script>\n</body>`,
    );
  const target = new URL(output, folder);
  await writeFile(
    target,
    "<!-- Generated by scripts/home-concepts/build.mjs. Edit sources, then rebuild. -->\n" +
      license +
      portable,
  );
  console.log(
    `Built ${fileURLToPath(target)} (${Math.round(Buffer.byteLength(portable) / 1024)} KiB, offline)`,
  );
}
await build("index.html", "design.html", ["styles.css"], common, true);
await build(
  "combined-index.html",
  "combined.html",
  ["styles.css", "combined.css"],
  [...common, "combined-icons.js", "combined-model.js", "combined-views.js", "combined-actions.js"],
);
