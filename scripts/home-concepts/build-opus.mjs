import { readFile, writeFile } from "node:fs/promises";

// Builds four self-contained Home prototypes from docs/audits/2026-10-09-home-concepts/opus/src.
// Shared: base.css, core.js, chrome.js, app.js. Each file adds one concept's .js/.css.
const root = new URL("../../", import.meta.url);
const out = new URL("docs/audits/2026-10-09-home-concepts/opus/", root);
const src = new URL("src/", out);
const read = (url) => readFile(url, "utf8");
const svg = async (name) =>
  (await read(new URL(`packages/app/assets/icons/${name}.svg`, root)))
    .replace(/<\?xml[^>]*>/, "")
    .replace(/\s+/g, " ")
    .trim();

const providerSvgs = JSON.stringify({ claude: await svg("claude"), codex: await svg("codex") });
const template = await read(new URL("template.html", src));
const base = await read(new URL("base.css", src));
const core = (await read(new URL("core.js", src))).replace("/*@PROVIDER_SVGS@*/ {}", providerSvgs);
const shared = [core, await read(new URL("chrome.js", src))];
const app = await read(new URL("app.js", src));
const concepts = [
  ["01-start", "Start"],
  ["02-hosts", "Hosts"],
  ["03-inbox", "Inbox"],
  ["04-home", "Home · tổng hòa"],
  ["05-app", "App · tabs + Hub"],
  // 06 builds on 05's Host/Hub and navigation parts.
  ["06-home", "Home = New workspace", ["c5-app", "c6-home"]],
];
for (const [file, title, parts = [`c${file.slice(1)}`]] of concepts) {
  const css = [base, ...(await Promise.all(parts.map((n) => read(new URL(`${n}.css`, src)))))].join(
    "\n",
  );
  const own = await Promise.all(parts.map((n) => read(new URL(`${n}.js`, src))));
  const js = [...shared, ...own, app].join("\n;\n");
  const html = template
    .replace("{{title}}", title)
    .replace("</head>", `<style>\n${css}\n</style>\n</head>`)
    .replace("</body>", `<script>\n${js.replaceAll("</script", "<\\/script")}\n</script>\n</body>`);
  await writeFile(
    new URL(`${file}.html`, out),
    `<!-- Generated by scripts/home-concepts/build-opus.mjs from opus/src; edit the sources. -->\n${html}`,
  );
  console.log(`${file}.html  ${Math.round(Buffer.byteLength(html) / 1024)} KiB`);
}
