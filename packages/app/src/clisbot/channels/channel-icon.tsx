const ThemedHash = withUnistyles(Hash);
const mutedIconMapping = (theme: Theme) => ({ color: theme.colors.foregroundMuted });

/**
 * The mark for a Channel (`slack`, `telegram`, …). A Channel without a mark here, or a snapshot
 * written before conversations recorded their Channel, falls back to a neutral `#`.
 */
export function ChannelIcon({
  channel,
  size = 12,
}: {
  channel: string | undefined;
  size?: number;
}): ReactElement {
  const mark = channel ? CHANNEL_MARKS[channel] : undefined;
  if (!mark) return <ThemedHash size={size} uniProps={mutedIconMapping} />;
  return <SvgPathIcon size={size} color={mark.color} path={mark.path} viewBox="0 0 24 24" />;
}

/**
 * A conversation's name as its Channel writes it: Slack channels as `#name` (the channel plane's
 * `resolveSlackChannelLabel` rule), Telegram groups by title. No recorded name shows the raw id.
 */
export function channelConversationLabel(conversation: {
  channel?: string;
  channelId: string;
  displayName?: string;
}): string {
  const name = conversation.displayName?.trim();
  if (!name) return conversation.channelId;
  return conversation.channel === "slack" && !name.startsWith("#") ? `#${name}` : name;
}
